# Caladrius population-simulation oracle, card T-158: the generated list of cases for the Rust tests.
#
# Reads the case files already on disk (oracle/expected/sim/**) and writes
# crates/caladrius-fit/tests/oracle_sim.cases, the lists and the macro calls that oracle_sim.rs includes.
# Nothing is computed: the file is an index. Names are sorted in byte order (C locale), as the Rust listers sort
# them, so the guard of oracle_sim.rs compares equal lists.
#
# Run: Rscript oracle/scripts/sim_index.R
suppressMessages(library(jsonlite))
src <- sub("^--file=", "", grep("^--file=", commandArgs(FALSE), value = TRUE)[1])
ROOT <- normalizePath(file.path(dirname(src), "..", ".."), winslash = "/", mustWork = TRUE)
EXP <- file.path(ROOT, "oracle", "expected", "sim")
OUT <- file.path(ROOT, "crates", "caladrius-fit", "tests", "oracle_sim.cases")
rd <- function(...) fromJSON(file.path(EXP, ...), simplifyVector = FALSE)
srt <- function(x) sort(x, method = "radix")
ids <- function(dir) srt(setdiff(sub("[.]json$", "", list.files(file.path(EXP, dir), pattern = "[.]json$")), "measure"))

kat <- rd("gen", "kat.json")
kat_ids <- srt(c(paste0("kat_", seq_along(kat$kat) - 1L), vapply(kat$blocks, function(b) b$name, "")))
stream_ids <- srt(vapply(rd("gen", "streams.json")$cases, function(c) c$name, ""))
exact_ids <- ids("exact")
study_ids <- ids("study")
quantile_ids <- srt(vapply(rd("quantile", "cases.json")$cases, function(c) c$name, ""))
invariance_ids <- srt(vapply(rd("invariance", "cases.json")$checks, function(c) c$name, ""))
rows <- rd("errors.json")$cases
constructible <- vapply(rows, function(r) if (is.null(r$constructible)) TRUE else isTRUE(r$constructible), TRUE)
expect <- vapply(rows, function(r) r$expect, "")
names_ <- vapply(rows, function(r) r$case, "")
roundtrip_ids <- ids("roundtrip")
all_names <- c(kat_ids, stream_ids, exact_ids, study_ids, quantile_ids, invariance_ids, names_, roundtrip_ids)
stopifnot(length(kat_ids) > 0, length(stream_ids) > 0, length(exact_ids) > 0, length(study_ids) > 0,
          length(quantile_ids) > 0, length(invariance_ids) > 0, length(rows) > 0, length(roundtrip_ids) > 0,
          !anyDuplicated(names_), all(grepl("^[A-Za-z][A-Za-z0-9_]*$", all_names)))

const_list <- function(name, x) c(sprintf("const %s: &[&str] = &[", name), sprintf("    \"%s\",", srt(x)), "];")
macro_call <- function(name, x) c(sprintf("%s!(", name), sprintf("    %s,", srt(x)), ");")

refused <- names_[expect == "refused" & constructible]
accepted <- names_[expect == "accepted" & constructible]
sentence <- names_[!constructible]
lines <- c(
  "// Generated by oracle/scripts/sim_index.R; do not edit by hand.",
  const_list("SIM_KAT", kat_ids),
  const_list("SIM_STREAMS", stream_ids),
  const_list("SIM_EXACT", exact_ids),
  const_list("SIM_STUDY", study_ids),
  const_list("SIM_QUANTILE", quantile_ids),
  const_list("SIM_INVARIANCE", invariance_ids),
  const_list("SIM_REFUSALS", refused),
  const_list("SIM_ACCEPTED", accepted),
  const_list("SIM_SENTENCE_ONLY", sentence),
  const_list("SIM_ROUNDTRIP", roundtrip_ids),
  macro_call("philox_tests", kat_ids),
  macro_call("stream_tests", stream_ids),
  macro_call("exact_tests", exact_ids),
  macro_call("study_tests", study_ids),
  macro_call("quantile_tests", quantile_ids),
  macro_call("invariance_tests", invariance_ids),
  macro_call("refusal_tests", refused),
  macro_call("accepted_tests", accepted),
  macro_call("roundtrip_tests", roundtrip_ids))
con <- file(OUT, open = "wb"); writeLines(lines, con, sep = "\n", useBytes = TRUE); close(con)
cat("sim_index: ", length(kat_ids), " kat/blocks, ", length(stream_ids), " streams, ", length(exact_ids), " exact, ",
    length(study_ids), " studies, ", length(quantile_ids), " quantile, ", length(invariance_ids), " invariance, ",
    length(refused), " refused, ", length(accepted), " accepted, ", length(sentence), " sentence-only, ",
    length(roundtrip_ids), " roundtrip; sha256 ",
    digest::digest(file = OUT, algo = "sha256", serialize = FALSE), "\n", sep = "")
